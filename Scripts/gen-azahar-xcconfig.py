#!/usr/bin/env python3
"""Write Azahar/build/engine.xcconfig and Azahar/build/engine-link.rsp from an Azahar CMake build.

The engine's compile flags (include paths, defines) and link inputs are decided by its CMake
files and change between Azahar versions. Copying them by hand into the Xcode project would
drift, so build-azahar-core.sh runs this after building, and the Xcode project reads the two
generated files.

Usage: gen-azahar-xcconfig.py <engine build dir> <output dir>
"""

import json
import os
import shlex
import sys

# A translation unit that includes the engine's headers the way our plugin will.
SAMPLE_SOURCE = "src/core/core.cpp"
# Frameworks the engine's libraries and the Vulkan code on macOS need at link time.
FRAMEWORKS = ["Cocoa", "AVFoundation", "IOSurface", "Metal", "QuartzCore", "CoreFoundation",
              "CoreAudio", "AudioToolbox", "Security", "SystemConfiguration"]


def quote(value):
    return '"%s"' % value.replace('"', '\\"') if (" " in value or "$" in value) else value


def compile_settings(build_dir):
    with open(os.path.join(build_dir, "compile_commands.json")) as f:
        entries = json.load(f)
    for entry in entries:
        if entry["file"].replace("\\", "/").endswith(SAMPLE_SOURCE):
            tokens = shlex.split(entry["command"]) if "command" in entry else entry["arguments"]
            break
    else:
        sys.exit("error: %s not found in compile_commands.json" % SAMPLE_SOURCE)

    includes, defines, flags = [], [], []
    i = 1
    while i < len(tokens):
        t = tokens[i]
        if t in ("-I", "-isystem", "-iquote"):
            includes.append(tokens[i + 1])
            i += 2
            continue
        if t.startswith("-I"):
            includes.append(t[2:])
        elif t.startswith("-isystem"):
            includes.append(t[len("-isystem"):])
        elif t == "-D":
            defines.append(tokens[i + 1])
            i += 2
            continue
        elif t.startswith("-D"):
            defines.append(t[2:])
        elif t.startswith(("-f", "-m")) and not t.startswith("-mmacosx-version-min"):
            flags.append(t)
        i += 1
    return includes, defines, flags


def static_libraries(build_dir):
    libs = []
    for root, _, files in os.walk(build_dir):
        if "CMakeFiles" in root.split(os.sep):
            continue
        for name in files:
            if name.endswith(".a"):
                libs.append(os.path.join(root, name))
    return sorted(libs)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    build_dir, out_dir = os.path.abspath(sys.argv[1]), os.path.abspath(sys.argv[2])
    os.makedirs(out_dir, exist_ok=True)

    includes, defines, flags = compile_settings(build_dir)
    with open(os.path.join(out_dir, "engine.xcconfig"), "w") as f:
        f.write("// Generated by Scripts/gen-azahar-xcconfig.py. Do not edit or commit.\n")
        f.write("ENGINE_HEADER_SEARCH_PATHS = %s\n" % " ".join(quote(p) for p in includes))
        f.write("ENGINE_DEFINES = %s\n" % " ".join(quote(d) for d in defines))
        f.write("ENGINE_CPLUSPLUSFLAGS = %s\n" % " ".join(quote(x) for x in flags))

    args = static_libraries(build_dir)
    for fw in FRAMEWORKS:
        args += ["-framework", fw]
    args += ["-lc++"]
    with open(os.path.join(out_dir, "engine-link.rsp"), "w") as f:
        f.write("\n".join(quote(a) for a in args) + "\n")
    print("Wrote %s and %s (%d libraries)" % (os.path.join(out_dir, "engine.xcconfig"),
                                              os.path.join(out_dir, "engine-link.rsp"), len(static_libraries(build_dir))))


if __name__ == "__main__":
    main()
