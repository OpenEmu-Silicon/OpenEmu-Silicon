#!/usr/bin/env python3
"""Write PCSX2/build/engine.xcconfig and PCSX2/build/engine-link.rsp from an ARMSX2 CMake build.

The engine's compile flags (include paths, defines) and link line are decided by its
CMake files and change between ARMSX2 versions. Copying them by hand into the Xcode
project would drift, so build-armsx2-core.sh runs this after configuring, and the
Xcode project reads the two generated files.

Usage: gen-armsx2-xcconfig.py <engine build dir> <output dir>
"""

import json
import os
import shlex
import sys

# A translation unit that includes the engine's headers the way our plugin will.
SAMPLE_SOURCE = "pcsx2/VMManager.cpp"
# The libretro target's link line is the full list of libraries a final binary needs.
LINK_TXT = os.path.join("pcsx2-libretro", "CMakeFiles", "pcsx2-libretro.dir", "link.txt")
LINK_CWD = "pcsx2-libretro"


def quote(value):
    return '"%s"' % value.replace('"', '\\"') if (" " in value or "$" in value) else value


def compile_settings(build_dir):
    with open(os.path.join(build_dir, "compile_commands.json")) as f:
        entries = json.load(f)
    for entry in entries:
        if entry["file"].replace("\\", "/").endswith(SAMPLE_SOURCE):
            tokens = shlex.split(entry["command"]) if "command" in entry else entry["arguments"]
            break
    else:
        sys.exit("error: %s not found in compile_commands.json" % SAMPLE_SOURCE)

    includes, defines, flags = [], [], []
    i = 1
    while i < len(tokens):
        t = tokens[i]
        if t in ("-I", "-isystem", "-iquote"):
            includes.append(tokens[i + 1])
            i += 2
            continue
        if t.startswith("-I"):
            includes.append(t[2:])
        elif t.startswith("-isystem"):
            includes.append(t[len("-isystem"):])
        elif t == "-D":
            defines.append(tokens[i + 1])
            i += 2
            continue
        elif t.startswith("-D"):
            defines.append(t[2:])
        elif t.startswith(("-f", "-m")) and not t.startswith("-mmacosx-version-min"):
            flags.append(t)
        elif t.startswith("-std="):
            pass  # Xcode sets the language standard itself (CLANG_CXX_LANGUAGE_STANDARD).
        i += 1
    return includes, defines, flags


def link_args(build_dir):
    path = os.path.join(build_dir, LINK_TXT)
    cwd = os.path.join(build_dir, LINK_CWD)
    with open(path) as f:
        tokens = shlex.split(f.read())
    out = []
    i = 1  # skip the compiler
    skip_next = {"-o", "-install_name", "-arch", "-isysroot", "-current_version", "-compatibility_version"}
    while i < len(tokens):
        t = tokens[i]
        if t in skip_next:
            i += 2
            continue
        if t in ("-shared", "-dynamiclib", "-bundle") or t.startswith(("-mmacosx-version-min", "-O", "-g")):
            i += 1
            continue
        if t.endswith("Main.cpp.o"):
            i += 1
            continue
        if not t.startswith("-") and not os.path.isabs(t) and t.endswith((".a", ".o", ".dylib", ".tbd")):
            t = os.path.normpath(os.path.join(cwd, t))
        out.append(t)
        i += 1
    return out


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    build_dir, out_dir = os.path.abspath(sys.argv[1]), os.path.abspath(sys.argv[2])
    os.makedirs(out_dir, exist_ok=True)

    includes, defines, flags = compile_settings(build_dir)
    with open(os.path.join(out_dir, "engine.xcconfig"), "w") as f:
        f.write("// Generated by Scripts/gen-armsx2-xcconfig.py. Do not edit or commit.\n")
        f.write("ENGINE_HEADER_SEARCH_PATHS = %s\n" % " ".join(quote(p) for p in includes))
        f.write("ENGINE_DEFINES = %s\n" % " ".join(quote(d) for d in defines))
        f.write("ENGINE_CPLUSPLUSFLAGS = %s\n" % " ".join(quote(x) for x in flags))

    with open(os.path.join(out_dir, "engine-link.rsp"), "w") as f:
        f.write("\n".join(quote(a) for a in link_args(build_dir)) + "\n")
    print("Wrote %s and %s" % (os.path.join(out_dir, "engine.xcconfig"), os.path.join(out_dir, "engine-link.rsp")))


if __name__ == "__main__":
    main()
